import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { pilotSchema } from "./pilot-contract.mjs";

/** Deterministic declaration output from the checked-in JSON Schema. */
export function declarations() {
  function type(schema) {
    if (schema === true) return "JsonValue";
    if (schema === false) return "never";
    if (schema.$ref) return schema.$ref.split("/").at(-1);
    if (schema.oneOf || schema.anyOf) return (schema.oneOf ?? schema.anyOf).map(type).join(" | ");
    if (Object.hasOwn(schema, "const")) return JSON.stringify(schema.const);
    if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(" | ");
    if (schema.type === "array") return schema.minItems === 2 && schema.maxItems === 2
      ? `[${type(schema.items)}, ${type(schema.items)}]` : `Array<${type(schema.items)}>`;
    if (schema.type === "object") {
      const fields = Object.entries(schema.properties ?? {}).map(([key, value]) =>
        `${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}: ${type(value)};`);
      if (schema.additionalProperties !== false) fields.push("[key: string]: JsonValue | undefined;");
      return `{ ${fields.join(" ")} }`;
    }
    return schema.type === "integer" ? "number" : schema.type;
  }
  return "// Generated by generate-pilot-types.mjs from pilot.schema.json. Do not edit.\n"
    + Object.entries(pilotSchema.$defs).map(([name, schema]) => `export type ${name} = ${type(schema)};\n`).join("");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL("./pilot.d.ts", import.meta.url), declarations());
}
